package com.nanolaba.nrg;

import com.nanolaba.nrg.core.TemplateManifest;
import com.nanolaba.nrg.core.json.MinimalJsonParser;
import com.nanolaba.nrg.widgets.NRGWidget;
import org.apache.commons.io.IOUtils;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.io.PrintStream;
import java.nio.charset.Charset;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

/**
 * Backs {@code nrg --claude-hook pre-edit|post-edit}, the Claude Code hooks of the NRG plugin.
 * The hook JSON arrives on stdin; the edited path is {@code tool_input.file_path}.
 *
 * <ul>
 *   <li>{@code pre-edit} (PreToolUse on Edit / Write) refuses an edit of a generated file with
 *       exit code 2 and names the template to edit instead — Claude Code shows the stderr text
 *       to the agent as the reason.</li>
 *   <li>{@code post-edit} (PostToolUse) finds the templates that read the edited file, validates
 *       them and regenerates their outputs. Errors go to stderr with exit code 2, which Claude
 *       Code feeds back to the agent; on success the regenerated files are reported as
 *       {@code additionalContext} JSON on stdout.</li>
 * </ul>
 *
 * <p>A hook must never get in the way of work it does not understand: unreadable input, a
 * project without templates or any internal failure ends with exit code 0 and no output.
 */
final class ClaudeHook {

    private final Charset charset;
    private final List<NRGWidget> widgets;
    private final Function<String, String> env;

    ClaudeHook(Charset charset, List<NRGWidget> widgets) {
        this(charset, widgets, System::getenv);
    }

    /** @param env environment lookup; the project directory comes from {@code CLAUDE_PROJECT_DIR} */
    ClaudeHook(Charset charset, List<NRGWidget> widgets, Function<String, String> env) {
        this.charset = charset;
        this.widgets = widgets;
        this.env = env;
    }

    int run(String mode, InputStream stdin) {
        try {
            @SuppressWarnings("unchecked")
            Map<String, Object> event = (Map<String, Object>) MinimalJsonParser.parse(IOUtils.toString(stdin, StandardCharsets.UTF_8));
            @SuppressWarnings("unchecked")
            Map<String, Object> input = (Map<String, Object>) event.get("tool_input");
            String path = input == null ? null : (String) input.get("file_path");
            if (path == null) {
                return NRG.EXIT_OK;
            }
            File projectDir = projectDirectory(event);
            File file = new File(path).isAbsolute() ? new File(path) : new File(projectDir, path);
            ManifestCommand project = new ManifestCommand(charset, widgets, projectDir).load(Collections.emptyList());
            if ("pre-edit".equals(mode)) {
                return preEdit(project, file);
            }
            if ("post-edit".equals(mode)) {
                return postEdit(project, file);
            }
            System.err.println("--claude-hook expects pre-edit or post-edit, got '" + mode + "'");
            return NRG.EXIT_USAGE;
        } catch (RuntimeException | IOException e) {
            return NRG.EXIT_OK;
        }
    }

    private File projectDirectory(Map<String, Object> event) {
        String fromEnv = env.apply("CLAUDE_PROJECT_DIR");
        if (fromEnv != null && !fromEnv.isEmpty()) {
            return new File(fromEnv);
        }
        Object cwd = event.get("cwd");
        return cwd instanceof String ? new File((String) cwd) : new File(".");
    }

    private int preEdit(ManifestCommand project, File file) {
        for (TemplateManifest m : project.getManifests()) {
            if (m.producesOutput(file)) {
                System.err.println(project.path(file) + " is generated by NRG from " + project.path(m.getSource())
                        + ". Edit " + project.path(m.getSource()) + " (or the fragment it imports; "
                        + "nrg --locate " + project.path(file) + ":LINE names the line) and regenerate with: nrg -f "
                        + project.path(m.getSource()));
                return 2;
            }
        }
        return NRG.EXIT_OK;
    }

    private int postEdit(ManifestCommand project, File file) {
        List<String> affected = new ArrayList<>();
        for (TemplateManifest m : project.getManifests()) {
            if (m.readsInput(file)) {
                affected.add(m.getSource().getPath());
            }
        }
        if (affected.isEmpty()) {
            return NRG.EXIT_OK;
        }
        List<String> validate = new ArrayList<>();
        Collections.addAll(validate, "--validate", "--log-level", "error");
        validate.addAll(affected);
        Captured check = runQuietly(validate);
        if (check.code != NRG.EXIT_OK) {
            System.err.println("NRG: the edit leaves a template invalid; fix it before going on:");
            System.err.print(check.err);
            return 2;
        }
        List<String> generate = new ArrayList<>();
        Collections.addAll(generate, "--format", "json", "--log-level", "error");
        generate.addAll(affected);
        Captured generated = runQuietly(generate);
        if (generated.code != NRG.EXIT_OK) {
            System.err.println("NRG: regeneration failed:");
            System.err.print(generated.err);
            return 2;
        }
        List<String> written = new ArrayList<>();
        try {
            @SuppressWarnings("unchecked")
            Map<String, Object> report = (Map<String, Object>) MinimalJsonParser.parse(generated.out);
            @SuppressWarnings("unchecked")
            List<Map<String, Object>> files = (List<Map<String, Object>>) report.get("files");
            for (Map<String, Object> f : files) {
                if ("written".equals(f.get("status"))) {
                    written.add((String) f.get("output"));
                }
            }
        } catch (RuntimeException e) {
            return NRG.EXIT_OK;
        }
        String context = written.isEmpty()
                ? "NRG: the generated files are already up to date."
                : "NRG regenerated " + String.join(", ", written) + " from the templates; commit them together with the template."
                + (check.err.trim().isEmpty() ? "" : " Warnings from --validate: " + check.err.trim());
        System.out.println("{\"hookSpecificOutput\": {\"hookEventName\": \"PostToolUse\", \"additionalContext\": "
                + RunReport.str(context) + "}}");
        return NRG.EXIT_OK;
    }

    /** Runs NRG in-process with stdout and stderr captured, so the hook's own output stays clean. */
    private static Captured runQuietly(List<String> args) {
        PrintStream out = System.out;
        PrintStream err = System.err;
        ByteArrayOutputStream outBuffer = new ByteArrayOutputStream();
        ByteArrayOutputStream errBuffer = new ByteArrayOutputStream();
        int code;
        try {
            System.setOut(new PrintStream(outBuffer, true, "UTF-8"));
            System.setErr(new PrintStream(errBuffer, true, "UTF-8"));
            code = NRG.run(args.toArray(new String[0]));
        } catch (IOException e) {
            code = NRG.EXIT_TEMPLATE_ERROR;
        } finally {
            System.setOut(out);
            System.setErr(err);
        }
        return new Captured(code, new String(outBuffer.toByteArray(), StandardCharsets.UTF_8),
                new String(errBuffer.toByteArray(), StandardCharsets.UTF_8));
    }

    private static final class Captured {
        final int code;
        final String out;
        final String err;

        Captured(int code, String out, String err) {
            this.code = code;
            this.out = out;
            this.err = err;
        }
    }
}
